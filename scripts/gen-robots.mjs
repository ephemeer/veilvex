#!/usr/bin/env node
/**
 * Generates public/robots.txt at build time (npm "prebuild") so the Sitemap line always uses
 * the same base URL as the build (SITE_URL, see scripts/lib/site-url.mjs).
 *
 * Policy: everything is crawlable except the contact API; search engines and AI/LLM crawlers
 * (training, search and user-triggered fetchers) are explicitly welcome, and llms.txt is advertised.
 */
import fs from 'node:fs';
import path from 'node:path';
import { siteUrl } from './lib/site-url.mjs';

const site = siteUrl();

/** AI / LLM crawlers and answer engines that get an explicit group (RFC 9309: most specific group wins). */
const AI_AGENTS = [
  'GPTBot',
  'OAI-SearchBot',
  'ChatGPT-User',
  'ClaudeBot',
  'anthropic-ai',
  'PerplexityBot',
  'Google-Extended',
  'Googlebot',
  'Bingbot',
  'Applebot-Extended',
  'CCBot',
  'Amazonbot',
  'Meta-ExternalAgent',
  'DuckAssistBot',
];

const group = (agent) => `User-agent: ${agent}\nAllow: /\nDisallow: /api/\n`;

const robots = [
  '# robots.txt — Veilvex (generated by scripts/gen-robots.mjs, do not edit by hand)',
  `# LLM-friendly summary of this site: ${site}/llms.txt (full content: ${site}/llms-full.txt)`,
  '',
  '# Default: the whole site is public except the contact API (POST-only, noindex).',
  group('*'),
  '# Search engines and AI crawlers / answer engines are explicitly welcome.',
  ...AI_AGENTS.map(group),
  `Sitemap: ${site}/sitemap-index.xml`,
  '',
].join('\n');

const out = path.resolve('public/robots.txt');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, robots);
console.log(`robots.txt → ${path.relative(process.cwd(), out)} (${AI_AGENTS.length + 1} groups, sitemap ${site}/sitemap-index.xml)`);
